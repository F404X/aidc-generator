const STANDARD_SAMPLES = Object.freeze({
  matrix: ['HELLO','123','123456','HELLO-2026'],
  linear: ['123456','12345678','123456789012','ABC123','A123456B'],
  stacked: ['HELLO','12345678','ABC12345'],
  postal: ['123456789','12345678901','1234567-890'],
});

/** Ordered fixtures, first valid result wins; a candidate is not displayed
 * unless the actual encoder accepted it. */
export function thumbnailSamples(format) {
  const sample=String(format.example||'').trim();
  const placeholders=/^(Swiss payment|Structured |GS1 coupon data|BWIPP raw patterns)/i.test(sample);
  const defaults=STANDARD_SAMPLES[format.kind]||STANDARD_SAMPLES.matrix;
  const candidates=[
    ...(SPECIAL[format.id]||[]),
    ...(!placeholders&&sample?[sample]:[]),
    ...(format.category==='gs1'?['(01)09506000134352','09506000134352']:[]),
    ...(format.category==='health'?['+A123BJC5D6E']:[]),
    ...(format.category==='postal'?STANDARD_SAMPLES.postal:[]),
    ...defaults,
  ];
  return [...new Set(candidates.filter(Boolean))];
}

const pause=()=>new Promise(resolve=>setTimeout(resolve,0));

/** Direct SVG: avoids two extra browser image decodes and a raster canvas.
 * The embedded output retains its natural ratio via CSS object-fit:contain. */
async function encodeThumb(format) {
  try {
    await ensureEngine('bwip');
  } catch {
    return {url:null,sample:null};
  }
  const candidates=thumbnailSamples(format);
  for(let i=0;i<candidates.length;i++){
    try{
      const sample=candidates[i];
      const options={
        bcid:format.id,
        text:prepareBarcodePayload(format,sample),
        scale:1,
        includetext:false,
        paddingwidth:2,
        paddingheight:2,
        barcolor:'151515',
        ...(format.kind==='linear'?{height:10}:{}),
        ...(REQUIRED_OPTIONS[format.id]||{}),
      };
      if(['datamatrix','gs1datamatrix','hibcdatamatrix'].includes(format.id)){
        options.format='square';
      }
      // Avoid iterating across every rMQR version for each specimen.
      if(format.id==='rectangularmicroqrcode')options.version='R11x59';
      const svg=window.bwipjs.toSVG(options);
      if(!svg.includes('<svg')||svg.length<80)throw Error('Empty barcode drawing');
      return {url:URL.createObjectURL(new Blob([svg],{type:'image/svg+xml;charset=utf-8'})),sample};
    }catch{
      // Hand control back to the browser between expensive special-case attempts.
      if(i%2===1)await pause();
    }
  }
  return {url:null,sample:null};
}

function drain() {
  while(busy<3&&queue.length){
    const {format,resolve}=queue.shift();
    busy++;
    void encodeThumb(format)
      .then(resolve,()=>resolve({url:null,sample:null}))
      .finally(()=>{busy--;drain();});
  }
}
function load(format) {
  if(!cache.has(format.id)){
    cache.set(format.id,new Promise(resolve=>{queue.push({format,resolve});drain();}));
  }
  return cache.get(format.id);
}
function show(frame,format) {
  void load(format).then(({url,sample})=>{
    if(!frame.isConnected)return;
    frame.classList.remove('is-loading');
    const label=frame.parentElement?.querySelector('.thumb-sample');
    if(!url){
      frame.classList.add('is-unavailable');
      frame.textContent='Special input';
      frame.title='This symbology requires a structured, standards-compliant example';
      if(label)label.textContent='Structured data required';
      return;
    }
    const image=document.createElement('img');
    image.className='thumb-image';
    image.alt=format.name+' example: '+sample;
    image.decoding='async';
    image.loading='lazy';
    image.src=url;
    frame.replaceChildren(image);
    frame.title='Encoded example: '+sample;
    if(label){
      label.textContent='Sample: '+String(sample).replace(/\s+/g,' ').slice(0,64);
      label.title=sample;
    }
  });
}
export function observeThumbnail(frame,format) {
  frame.dataset.formatId=format.id;
  if(!('IntersectionObserver' in window)){show(frame,format);return;}
  if(!observer){
    observer=new IntersectionObserver(entries=>{
      for(const entry of entries){
        if(!entry.isIntersecting)continue;
        const target=entry.target;
        observer.unobserve(target);
        show(target,lookupFormat(target.dataset.formatId));
      }
    },{rootMargin:'125px 0px'});
  }
  observer.observe(frame);
}
export function unobserveThumbnails(container) {
  if(observer)container.querySelectorAll('.code-thumb').forEach(frame=>observer.unobserve(frame));
}
if(typeof window!=='undefined')window.addEventListener('pagehide',()=>{
  for(const value of cache.values()){
    void value.then(item=>{if(item.url)URL.revokeObjectURL(item.url);});
  }
});
